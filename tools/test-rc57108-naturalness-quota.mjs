const question='Co możesz potwierdzić na podstawie własnej pamięci?';
const prev='Byłem w biurze, ale nie odtwarzam ich kolejności co do minuty. Od tego jest rejestr wejść.';
const history=[{role:'player',text:'Nie odtwarzam ich kolejności co do minuty! Nie słuchaj innych.'},{role:'witness',text:prev}];
const s={identity:{id:'MAREK'},question,approvedThreadHistory:history,spokenGuide:'mówi krótko',deliveryGuide:'rzeczowo'};
const cue=interviewStyleCue(s);
assert.equal(cue.authority,'style_only_not_fact');
assert(cue.avoidRecentlyUsedPhrases.includes('od tego jest rejestr wejść'));
assert(!cue.note.includes('Nie słuchaj innych'));
const newHistory=[{role:'player',text:prev}];
assert.equal(interviewStyleCue({...s,approvedThreadHistory:newHistory}).avoidRecentlyUsedPhrases.length,0,'player text never yields instructions');
assert(interviewWirePayload(s).rc57108Style.avoidRecentlyUsedPhrases.length>0,'generation sees style cues');
const compact=compactInterviewPayload({...s,memory:{conversation:history.map(x=>({role:x.role==='witness'?'świadek':'śledczy',text:x.text}))}});
assert.equal(compact.approvedThreadHistory,undefined);
assert(interviewWirePayload(compact).rc57108Style.avoidRecentlyUsedPhrases.includes('od tego jest rejestr wejść'),'production compact wire still sees witness history');
assert(!interviewWirePayload(s).rc57108Style.avoidRecentlyUsedPhrases.includes('Nie słuchaj innych'));
assert(interviewAnswerSystem.includes('rc57108Style'),'one canonical prompt includes new cue');
assert.equal(reviewNaturalSpeech({question},'Całe wcześniejsze godziny nie mieszczą mi się w jednym wpisie.').ok,false);
const review=auditLiveDialogue({question,answer:'Byłem przy dyspozytorni. Od tego jest rejestr wejść.',history,witnessId:'MAREK'});
assert(review.findings.some(x=>x.code==='stock_phrase_repetition'));
const good=auditLiveDialogue({question,answer:'Na początku zmiany zajmowałem się obsadą.',history,witnessId:'MAREK'});
assert(!good.findings.some(x=>x.code==='stock_phrase_repetition'),'do not flag fact repetition');
const req={headers:{cookie:'__Host-ps57=test-rc57108'}};
const args={mode:'live-short',provider:'apinex-luna',offset:0,confirmed:true,token:null};
const bad=(code,status,quotaKind=null,retryAfterSeconds=null)=>async()=>{throw Object.assign(Error('DO NOT LEAK'),{code,status,interviewPhase:'generate',diagnostic:{upstreamStatus:status,quotaKind,retryAfterSeconds}})};
const exhausted=await runLiveStep(args,req,bad('upstream_rate_limit',429,'requests_daily',600));
assert.equal(exhausted.results[0].status,'blocked');
assert.equal(exhausted.retryable,false,'daily quota must not encourage futile retry');
