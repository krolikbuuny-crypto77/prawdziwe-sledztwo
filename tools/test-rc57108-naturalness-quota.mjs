assert(!JSON.stringify(exhausted).includes('DO NOT LEAK'));
const invalid=await runLiveStep(args,req,bad('upstream_invalid_request',400));
assert.equal(invalid.stopped,'provider_invalid_request');assert.equal(invalid.retryable,false);
const auth=await runLiveStep(args,req,bad('upstream_authorization',403));
assert.equal(auth.stopped,'provider_authorization_failed');assert.equal(auth.retryable,false);
const timeout=await runLiveStep(args,req,bad('model_timeout',504));
assert.equal(timeout.stopped,'provider_timeout');assert.equal(timeout.retryable,true);assert.equal(timeout.retryOffset,0);
