import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../src/integrations/35-zai-client.js', import.meta.url),'utf8');
const html=fs.readFileSync(new URL('../index.html', import.meta.url),'utf8');
const start=source.indexOf('function showBusy(value){');
const end=source.indexOf('\n function send()',start);
assert(start>=0&&end>start,'showBusy cannot be extracted');
const snippet=source.slice(start,end);
const status={style:{display:'none'},textContent:''};
const send={disabled:false},input={disabled:false};
const context={status,send,input,inflight:false,cloudFailure:'',by:id=>id==='chatSend'?send:id==='chatInput'?input:null};
vm.createContext(context);
vm.runInContext(snippet+'\nthis.showBusy=showBusy;',context);
context.showBusy(true);
assert.equal(status.style.display,'none','No AI waiting banner while request runs');
assert.equal(status.textContent,'','No AI waiting copy while request runs');
assert.equal(send.disabled,true);
assert.equal(input.disabled,true);
context.showBusy(false);
assert.equal(status.style.display,'none','Hide banner after success');
assert.equal(send.disabled,false);
assert.equal(input.disabled,false);
context.cloudFailure='Nie można odpowiedzieć. Ponów pytanie.';
context.showBusy(false);
assert.equal(status.style.display,'block','Keep errors visible');
assert.equal(status.textContent,context.cloudFailure);
assert(!html.includes('Świadek przygotowuje odpowiedź przez AI…'),'Compiled HTML cannot show technical waiting string');
assert(html.includes("message.textContent='Formułuje odpowiedź…'"),'Keep neutral in-chat waiting state');
console.log('PASS: no visible AI waiting label; neutral in-chat state; errors still visible; controls disabled while waiting');
